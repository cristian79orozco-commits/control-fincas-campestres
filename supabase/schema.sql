-- 8. CONFIGURACIÓN DEL BUCKET DE ALMACENAMIENTO (SUPABASE STORAGE)
-- Insertar el bucket finca-imagenes si no existe
INSERT INTO storage.buckets (id, name, public)
VALUES ('finca-imagenes', 'finca-imagenes', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- Políticas de Storage
CREATE POLICY "Imágenes de fincas públicas"
    ON storage.objects FOR SELECT
    TO anon, authenticated
    USING (bucket_id = 'finca-imagenes');

CREATE POLICY "Subida de imágenes autenticada"
    ON storage.objects FOR INSERT
    TO authenticated
    WITH CHECK (bucket_id = 'finca-imagenes');

CREATE POLICY "Eliminación de imágenes autenticada"
    ON storage.objects FOR DELETE
    TO authenticated
    USING (bucket_id = 'finca-imagenes');
